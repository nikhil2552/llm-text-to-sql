"""Config Generator - transforms stack discovery results into connector YAML configs."""

import logging
from dataclasses import dataclass
from pathlib import Path

import yaml

from llm_sql.connectors.stack_discovery import StackInfo

logger = logging.getLogger(__name__)


@dataclass
class GenerationResult:
    """Result of attempting to generate a connector config."""

    connector_type: str
    action: str  # 'created', 'skipped', 'unavailable', 'error'
    file_path: str | None = None
    reason: str | None = None


class ConfigGenerator:
    """Generates connector YAML configs from stack discovery results."""

    def __init__(self, config_dir: Path | None = None):
        """Initialize with target config directory.

        Args:
            config_dir: Path to the directory where YAML configs are written.
                        Defaults to config/connections/.
        """
        self.config_dir = config_dir or Path("config/connections/")

    def generate_all(self, stacks: list[StackInfo], region: str) -> list[GenerationResult]:
        """Generate configs for all discovered stacks. Skip existing.

        Args:
            stacks: List of StackInfo objects from stack discovery.
            region: AWS region string for config settings.

        Returns:
            List of GenerationResult objects describing what happened for each connector.
        """
        results: list[GenerationResult] = []

        # Ensure config directory exists
        self.config_dir.mkdir(parents=True, exist_ok=True)

        # Map stack types to their generation logic
        generators = {
            "main": ("athena", self.generate_athena_config, "athena_auto.yaml"),
            "rds": ("rds_mysql", self.generate_rds_config, "rds_mysql_auto.yaml"),
            "redshift": ("redshift", self.generate_redshift_config, "redshift_auto.yaml"),
        }

        for stack_info in stacks:
            if stack_info.stack_type not in generators:
                continue

            connector_type, gen_func, filename = generators[stack_info.stack_type]

            # Check if stack is available
            if not stack_info.available:
                results.append(
                    GenerationResult(
                        connector_type=connector_type,
                        action="unavailable",
                        reason=f"Stack '{stack_info.stack_name}' is not available",
                    )
                )
                continue

            # Check for existing config
            if self._has_existing_config(connector_type):
                logger.info(
                    "Skipping %s config generation - existing config found.",
                    connector_type,
                )
                results.append(
                    GenerationResult(
                        connector_type=connector_type,
                        action="skipped",
                        reason=f"Existing config with type '{connector_type}' already present",
                    )
                )
                continue

            # Generate config dict
            try:
                config = gen_func(stack_info, region)
            except Exception as e:
                logger.error(
                    "Error generating %s config: %s", connector_type, e
                )
                results.append(
                    GenerationResult(
                        connector_type=connector_type,
                        action="error",
                        reason=f"Config generation failed: {e}",
                    )
                )
                continue

            # Write YAML file
            file_path = self.config_dir / filename
            try:
                yaml_content = self.config_to_yaml(config)
                file_path.write_text(
                    f"# Auto-generated by stack discovery\n{yaml_content}",
                    encoding="utf-8",
                )
                logger.info("Created %s config at %s", connector_type, file_path)
                results.append(
                    GenerationResult(
                        connector_type=connector_type,
                        action="created",
                        file_path=str(file_path),
                    )
                )
            except OSError as e:
                logger.error(
                    "Failed to write %s config to %s: %s",
                    connector_type,
                    file_path,
                    e,
                )
                results.append(
                    GenerationResult(
                        connector_type=connector_type,
                        action="error",
                        reason=f"Failed to write file: {e}",
                    )
                )

        return results

    def generate_athena_config(self, stack_info: StackInfo, region: str) -> dict:
        """Transform main stack outputs into Athena connector config dict.

        Args:
            stack_info: StackInfo with main stack outputs.
            region: AWS region string.

        Returns:
            Config dict ready for YAML serialization.
        """
        outputs = stack_info.outputs

        # Build comma-separated list of Glue database names
        db_names = []
        if outputs.get("LibraryDatabaseName"):
            db_names.append(outputs["LibraryDatabaseName"])
        if outputs.get("CarsDatabaseName"):
            db_names.append(outputs["CarsDatabaseName"])
        glue_db_names = ",".join(db_names)

        return {
            "name": "Athena (Auto-detected)",
            "type": "athena",
            "enabled": True,
            "settings": {
                "glue_db_names": glue_db_names,
                "s3_bucket": outputs["ProjectfilesBucketName"],
                "workgroup": outputs["AthenaWorkgroupName"],
                "region": region,
            },
        }

    def generate_rds_config(self, stack_info: StackInfo, region: str) -> dict:
        """Transform RDS stack outputs into RDS MySQL connector config dict.

        Args:
            stack_info: StackInfo with RDS stack outputs.
            region: AWS region string.

        Returns:
            Config dict ready for YAML serialization.
        """
        outputs = stack_info.outputs

        return {
            "name": "RDS Aurora MySQL (Auto-detected)",
            "type": "rds_mysql",
            "enabled": True,
            "settings": {
                "host": outputs["ClusterEndpoint"],
                "port": int(outputs["ClusterPort"]),
                "database": outputs["DatabaseName"],
                "user_from_secret": outputs["SecretName"],
                "region": region,
            },
        }

    def generate_redshift_config(self, stack_info: StackInfo, region: str) -> dict:
        """Transform Redshift stack outputs into Redshift connector config dict.

        Args:
            stack_info: StackInfo with Redshift stack outputs.
            region: AWS region string.

        Returns:
            Config dict ready for YAML serialization.
        """
        outputs = stack_info.outputs

        # Determine secret name: try to parse from ConnectionConfig, fallback to stack-based name
        secret_name = self._extract_redshift_secret_name(stack_info)

        return {
            "name": "Redshift Serverless (Auto-detected)",
            "type": "redshift",
            "enabled": True,
            "settings": {
                "host": outputs["RedshiftWorkgroupEndpoint"],
                "port": 5439,
                "database": outputs["RedshiftDatabase"],
                "schema": "public",
                "user_from_secret": secret_name,
                "region": region,
            },
        }

    def _extract_redshift_secret_name(self, stack_info: StackInfo) -> str:
        """Extract secret name from Redshift stack outputs.

        Attempts to parse the ConnectionConfig output for a secret reference.
        Falls back to a conventional name based on the stack name.

        Args:
            stack_info: StackInfo with Redshift stack outputs.

        Returns:
            Secret name string (reference only, never a secret value).
        """
        connection_config = stack_info.outputs.get("ConnectionConfig", "")

        # Try to parse secret name from ConnectionConfig (may contain JSON or key=value)
        if connection_config:
            try:
                import json

                parsed = json.loads(connection_config)
                if isinstance(parsed, dict):
                    # Look for secret name keys
                    for key in ("secret_name", "secretName", "user_from_secret"):
                        if key in parsed:
                            return parsed[key]
            except (json.JSONDecodeError, TypeError):
                pass

            # Check if ConnectionConfig itself looks like a secret name reference
            if "/" in connection_config and " " not in connection_config:
                return connection_config

        # Fallback: construct from stack name
        return f"{stack_info.stack_name}/redshift-credentials"

    def _has_existing_config(self, connector_type: str) -> bool:
        """Check if a config with matching type field already exists.

        Scans all YAML files in the config directory for a file whose 'type'
        field matches the given connector_type. Both enabled and disabled
        configs are considered as existing.

        Args:
            connector_type: The connector type to search for (e.g. 'athena', 'rds_mysql').

        Returns:
            True if an existing config with matching type is found.
        """
        if not self.config_dir.exists():
            return False

        for yaml_file in self.config_dir.glob("*.yaml"):
            try:
                content = yaml_file.read_text(encoding="utf-8")
                data = yaml.safe_load(content)
                if isinstance(data, dict) and data.get("type") == connector_type:
                    return True
            except (yaml.YAMLError, OSError) as e:
                # Treat malformed YAML as existing (do not overwrite)
                logger.warning(
                    "Could not parse %s, treating as existing config: %s",
                    yaml_file,
                    e,
                )
                return True

        return False

    @staticmethod
    def config_to_yaml(config: dict) -> str:
        """Serialize config dict to YAML string.

        Args:
            config: Configuration dictionary to serialize.

        Returns:
            YAML-formatted string representation.
        """
        return yaml.dump(
            config,
            default_flow_style=False,
            sort_keys=False,
            allow_unicode=True,
        )
